[CmdletBinding()]
param(
    [string]$JdkPath,
    [string]$RuntimePath,
    [string]$PackageOutputPath,
    [ValidatePattern('^[A-Za-z0-9][A-Za-z0-9_-]{0,47}$')]
    [string]$BuildVariant
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$buildRoot = Join-Path $projectRoot 'build'
if ($BuildVariant) { $buildRoot = Join-Path $buildRoot $BuildVariant }
$classesPath = Join-Path $buildRoot 'classes'
$inputPath = Join-Path $buildRoot 'input'
$sourcePath = Join-Path $projectRoot 'src\main\java'
$resourcePath = Join-Path $projectRoot 'src\main\resources'
$markerPath = Join-Path $buildRoot '.wordnest-generated'
$dependencyPath = Join-Path $projectRoot 'lib'
$flatLafName = 'flatlaf-3.7.2.jar'
$flatLafPath = Join-Path $dependencyPath $flatLafName
$dependencyHashes = @{
    'flatlaf-3.7.2.jar' = '917aff3963c88d797d0fd9b9ccbd70f7681c101df9d11c59e2bc7a3a6c0fabf4'
    'flatlaf-3.7.2-windows-x86_64.dll' = '533407841892e294f70e4f1443ebddecbea83b7f0bd2af876181505073b677d5'
}

function Resolve-Jdk {
    param([string]$RequestedPath)
    if ($RequestedPath) {
        $candidate = [IO.Path]::GetFullPath($RequestedPath)
        if (-not (Test-Path -LiteralPath (Join-Path $candidate 'bin\javac.exe'))) {
            throw "No javac.exe was found in the requested JDK: $candidate"
        }
        return $candidate
    }
    if ($env:JAVA_HOME -and (Test-Path -LiteralPath (Join-Path $env:JAVA_HOME 'bin\javac.exe'))) {
        return [IO.Path]::GetFullPath($env:JAVA_HOME)
    }
    $javacCommand = Get-Command javac.exe -ErrorAction SilentlyContinue
    if ($javacCommand) {
        $candidate = Split-Path (Split-Path $javacCommand.Source -Parent) -Parent
        if (Test-Path -LiteralPath (Join-Path $candidate 'bin\jar.exe')) { return $candidate }
    }
    $javaFolder = Join-Path $env:ProgramFiles 'Java'
    if (Test-Path -LiteralPath $javaFolder) {
        $installed = @(Get-ChildItem -LiteralPath $javaFolder -Directory |
            Where-Object { Test-Path -LiteralPath (Join-Path $_.FullName 'bin\javac.exe') } |
            Sort-Object Name -Descending)
        if ($installed.Count -gt 0) { return $installed[0].FullName }
    }
    throw 'A JDK 17 or newer is required. Install a JDK or pass -JdkPath.'
}

function Reset-GeneratedDirectory {
    param([string]$Directory)
    $resolvedDirectory = [IO.Path]::GetFullPath($Directory)
    $allowed = @([IO.Path]::GetFullPath($classesPath), [IO.Path]::GetFullPath($inputPath))
    if ($resolvedDirectory -notin $allowed) {
        throw "Refusing to clean a directory outside the generated build folders: $resolvedDirectory"
    }
    if (Test-Path -LiteralPath $resolvedDirectory) {
        if (-not (Test-Path -LiteralPath $markerPath)) {
            throw "Build ownership marker is missing. Preserve or move this folder before rebuilding: $buildRoot"
        }
        $folder = Get-Item -LiteralPath $resolvedDirectory -Force
        if (($folder.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw "Refusing to remove a linked build folder: $resolvedDirectory"
        }
        Remove-Item -LiteralPath $resolvedDirectory -Recurse -Force
    }
    New-Item -ItemType Directory -Path $resolvedDirectory -Force | Out-Null
}

$JdkPath = Resolve-Jdk $JdkPath
foreach ($name in $dependencyHashes.Keys) {
    $dependency = Join-Path $dependencyPath $name
    if (-not (Test-Path -LiteralPath $dependency -PathType Leaf)) {
        throw "Missing bundled dependency: $dependency. See licenses/FlatLaf-NOTICE.md."
    }
    if ((Get-FileHash -LiteralPath $dependency -Algorithm SHA256).Hash -ne $dependencyHashes[$name]) {
        throw "Dependency checksum mismatch: $dependency"
    }
}
$javac = Join-Path $JdkPath 'bin\javac.exe'
$jar = Join-Path $JdkPath 'bin\jar.exe'
$jpackage = Join-Path $JdkPath 'bin\jpackage.exe'
$sources = @(Get-ChildItem -LiteralPath $sourcePath -Filter '*.java' -Recurse -File |
    Sort-Object FullName | ForEach-Object { $_.FullName })
if ($sources.Count -eq 0) { throw "No Java source files found under $sourcePath" }

if (Test-Path -LiteralPath $buildRoot) {
    $buildInfo = Get-Item -LiteralPath $buildRoot -Force
    if (($buildInfo.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Refusing to use a linked build root: $buildRoot"
    }
    if (-not (Test-Path -LiteralPath $markerPath)) {
        if ((Test-Path -LiteralPath $classesPath) -or (Test-Path -LiteralPath $inputPath)) {
            throw "An unmarked build folder exists. Preserve or move it before rebuilding: $buildRoot"
        }
    }
}
New-Item -ItemType Directory -Path $buildRoot -Force | Out-Null
Set-Content -LiteralPath $markerPath -Value 'Generated by WordNest scripts/build.ps1; classes and input can be rebuilt.' -Encoding UTF8
Reset-GeneratedDirectory $classesPath
Reset-GeneratedDirectory $inputPath

Write-Host "Compiling with $JdkPath (Java 17 target)..."
& $javac --release 17 -encoding UTF-8 -classpath $flatLafPath -d $classesPath @sources
if ($LASTEXITCODE -ne 0) { throw "javac failed with exit code $LASTEXITCODE" }

if (Test-Path -LiteralPath $resourcePath) {
    Get-ChildItem -LiteralPath $resourcePath -Force | ForEach-Object {
        Copy-Item -LiteralPath $_.FullName -Destination $classesPath -Recurse -Force
    }
}
$jarPath = Join-Path $inputPath 'wordnest.jar'
$packagedLib = Join-Path $inputPath 'lib'
New-Item -ItemType Directory -Path $packagedLib -Force | Out-Null
foreach ($name in $dependencyHashes.Keys) {
    Copy-Item -LiteralPath (Join-Path $dependencyPath $name) -Destination $packagedLib -Force
}
$manifestPath = Join-Path $buildRoot 'MANIFEST.MF'
Set-Content -LiteralPath $manifestPath -Value "Class-Path: lib/$flatLafName`n" -Encoding ascii
& $jar --create --file $jarPath --main-class wordnest.App --manifest $manifestPath -C $classesPath .
if ($LASTEXITCODE -ne 0) { throw "jar failed with exit code $LASTEXITCODE" }
Write-Host "JAR created: $jarPath"

if (-not $RuntimePath) {
    Write-Host 'Pass -RuntimePath <portable JRE folder> to also build a standalone Windows app.'
    return
}

$RuntimePath = [IO.Path]::GetFullPath($RuntimePath)
if (-not (Test-Path -LiteralPath (Join-Path $RuntimePath 'bin\java.exe'))) {
    throw "The runtime folder does not contain bin\java.exe: $RuntimePath"
}
if (-not (Test-Path -LiteralPath $jpackage)) {
    throw "jpackage.exe was not found in $JdkPath. Use a complete JDK 17 or newer."
}
if (-not $PackageOutputPath) {
    $PackageOutputPath = Join-Path (Split-Path $projectRoot -Parent) 'WordNest-Windows'
}
$PackageOutputPath = [IO.Path]::GetFullPath($PackageOutputPath)
if (Test-Path -LiteralPath (Join-Path $PackageOutputPath 'WordNest')) {
    $PackageOutputPath += '-' + (Get-Date -Format 'yyyyMMdd-HHmmss-fff')
    Write-Host "An earlier package was preserved. New destination: $PackageOutputPath"
}
$packageArguments = @(
    '--type', 'app-image',
    '--name', 'WordNest',
    '--app-version', '0.4.1',
    '--vendor', 'WordNest',
    '--description', 'Offline English-Chinese desktop dictionary and vocabulary notebook',
    '--input', $inputPath,
    '--main-jar', 'wordnest.jar',
    '--main-class', 'wordnest.App',
    '--runtime-image', $RuntimePath,
    '--dest', $PackageOutputPath,
    '--java-options', '-Xmx512m',
    '--java-options', '-Dfile.encoding=UTF-8'
)
$iconPath = Join-Path $resourcePath 'app.ico'
if (Test-Path -LiteralPath $iconPath) { $packageArguments += @('--icon', $iconPath) }
Write-Host 'Creating a portable Windows app (no installer or system changes)...'
& $jpackage @packageArguments
if ($LASTEXITCODE -ne 0) { throw "jpackage failed with exit code $LASTEXITCODE" }
$appPath = Join-Path $PackageOutputPath 'WordNest'
Copy-Item -LiteralPath (Join-Path $resourcePath 'expanded-coverage.tsv') -Destination (Join-Path $appPath 'learning-coverage.tsv') -Force
$licensesPath = Join-Path $projectRoot 'licenses'
if (Test-Path -LiteralPath $licensesPath) {
    Copy-Item -LiteralPath $licensesPath -Destination $appPath -Recurse -Force
}
foreach ($document in @('README.md', '使用说明.txt', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md', 'LEARNING_COVERAGE.md', 'CURATED_COVERAGE.md', 'VALIDATION.md', 'LICENSE')) {
    $documentPath = Join-Path $projectRoot $document
    if (Test-Path -LiteralPath $documentPath) {
        Copy-Item -LiteralPath $documentPath -Destination $appPath -Force
    }
}
Write-Host "Portable application created: $(Join-Path $appPath 'WordNest.exe')"
